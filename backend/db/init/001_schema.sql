CREATE TABLE conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_type VARCHAR(20) NOT NULL,
    name VARCHAR(100),
    creator_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    direct_user_low_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    direct_user_high_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    last_message_id BIGINT,
    last_message_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uq_conversations_direct_pair UNIQUE (
        direct_user_low_id,
        direct_user_high_id
    ),
    CONSTRAINT chk_conversations_type CHECK (
        conversation_type IN ('private', 'group')
    ),
    CONSTRAINT chk_conversations_private_pair CHECK (
        (
            conversation_type = 'private'
            AND name IS NULL
            AND direct_user_low_id IS NOT NULL
            AND direct_user_high_id IS NOT NULL
            AND direct_user_low_id < direct_user_high_id
        )
        OR (
            conversation_type = 'group'
            AND btrim(COALESCE(name, '')) <> ''
            AND direct_user_low_id IS NULL
            AND direct_user_high_id IS NULL
        )
    )
);

CREATE TABLE conversation_members (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    member_role VARCHAR(20) NOT NULL DEFAULT 'member',
    membership_status VARCHAR(20) NOT NULL DEFAULT 'active',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    last_read_message_id BIGINT,
    is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
    is_muted BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT chk_conversation_members_role CHECK (
        member_role IN ('owner', 'member')
    ),
    CONSTRAINT chk_conversation_members_status CHECK (
        membership_status IN ('active', 'left', 'removed')
    ),
    CONSTRAINT chk_conversation_members_left_at CHECK (
        (membership_status = 'active' AND left_at IS NULL)
        OR (membership_status IN ('left', 'removed') AND left_at IS NOT NULL)
    )
);

CREATE OR REPLACE FUNCTION enforce_private_conversation_member()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    direct_low_id BIGINT;
    direct_high_id BIGINT;
    type_value VARCHAR(20);
BEGIN
    SELECT conversation_type, direct_user_low_id, direct_user_high_id
    INTO type_value, direct_low_id, direct_high_id
    FROM conversations
    WHERE id = NEW.conversation_id;

    IF type_value = 'private'
       AND NEW.user_id NOT IN (direct_low_id, direct_high_id) THEN
        RAISE EXCEPTION
            'private conversation member must belong to its direct user pair';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_conversation_members_private_pair
BEFORE INSERT OR UPDATE OF conversation_id, user_id ON conversation_members
FOR EACH ROW
EXECUTE FUNCTION enforce_private_conversation_member();

