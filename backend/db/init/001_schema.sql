CREATE OR REPLACE FUNCTION enforce_active_message_sender()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    PERFORM 1
    FROM conversation_members
    WHERE conversation_id = NEW.conversation_id
      AND user_id = NEW.sender_id
      AND membership_status = 'active';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'message sender must be an active conversation member';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_messages_active_sender
BEFORE INSERT ON messages
FOR EACH ROW
EXECUTE FUNCTION enforce_active_message_sender();

CREATE OR REPLACE FUNCTION update_conversation_last_message()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE conversations
    SET last_message_id = NEW.id,
        last_message_at = NEW.created_at,
        updated_at = CURRENT_TIMESTAMP
    WHERE id = NEW.conversation_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_messages_update_conversation_last_message
AFTER INSERT ON messages
FOR EACH ROW
EXECUTE FUNCTION update_conversation_last_message();

