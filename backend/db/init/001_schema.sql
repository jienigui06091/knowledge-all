CREATE OR REPLACE FUNCTION set_answer_accepted_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.is_accepted THEN
        IF TG_OP = 'INSERT' THEN
            NEW.accepted_at = CURRENT_TIMESTAMP;
        ELSIF NOT OLD.is_accepted THEN
            NEW.accepted_at = CURRENT_TIMESTAMP;
        END IF;
    ELSE
        NEW.accepted_at = NULL;
    END IF;

    RETURN NEW;
END;
$$;

